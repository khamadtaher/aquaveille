-- Eaux souterraines : points d'eau (référentiel BSS / ADES) et analyses physico-chimiques.

-- Seuils d'alerte propres aux nappes (indicatifs, inspirés des valeurs seuils
-- du bon état chimique des eaux souterraines). Null = pas d'alerte pour ce paramètre.
ALTER TABLE parametre ADD COLUMN seuil_min_nappe DOUBLE PRECISION;
ALTER TABLE parametre ADD COLUMN seuil_max_nappe DOUBLE PRECISION;

UPDATE parametre SET seuil_max_nappe = 50.0 WHERE code = '1340';  -- Nitrates
UPDATE parametre SET seuil_max_nappe = 0.5  WHERE code = '1335';  -- Ammonium

CREATE TABLE point_eau (
    bss_id                   VARCHAR(20)   NOT NULL PRIMARY KEY,
    code_bss                 VARCHAR(60),
    libelle                  VARCHAR(1000),
    commune                  VARCHAR(255),
    code_departement         VARCHAR(3),
    latitude                 DOUBLE PRECISION NOT NULL,
    longitude                DOUBLE PRECISION NOT NULL,
    nature                   VARCHAR(255),
    profondeur               DOUBLE PRECISION,
    mode_gisement            VARCHAR(255),
    caracteristique_aquifere VARCHAR(255),
    masses_eau               VARCHAR(2000),
    urn_bss                  VARCHAR(255)
);

CREATE INDEX idx_point_eau_departement ON point_eau (code_departement);

-- Entités hydrogéologiques BDLISA rattachées au point (plusieurs si forage multicouche).
CREATE TABLE point_eau_entite (
    point_bss_id VARCHAR(20)   NOT NULL,
    ordre        INTEGER       NOT NULL,
    code         VARCHAR(20)   NOT NULL,
    nom          VARCHAR(1000),
    CONSTRAINT pk_point_eau_entite PRIMARY KEY (point_bss_id, ordre),
    CONSTRAINT fk_entite_point FOREIGN KEY (point_bss_id) REFERENCES point_eau (bss_id) ON DELETE CASCADE
);

CREATE TABLE mesure_nappe (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_bss_id     VARCHAR(20)  NOT NULL,
    parametre_code   VARCHAR(10)  NOT NULL,
    date_prelevement DATE         NOT NULL,
    valeur           DOUBLE PRECISION NOT NULL,
    hors_seuil       BOOLEAN      NOT NULL,
    CONSTRAINT uk_mesure_nappe UNIQUE (point_bss_id, parametre_code, date_prelevement),
    CONSTRAINT fk_mesure_nappe_point FOREIGN KEY (point_bss_id) REFERENCES point_eau (bss_id),
    CONSTRAINT fk_mesure_nappe_parametre FOREIGN KEY (parametre_code) REFERENCES parametre (code)
);

CREATE INDEX idx_mesure_nappe_point_date ON mesure_nappe (point_bss_id, date_prelevement);
CREATE INDEX idx_mesure_nappe_alerte ON mesure_nappe (hors_seuil, date_prelevement);
